export function evaluateContrast(css: string) {
  const colors = parseColors(css);
  return pairs.map((pair) => {
    const foregroundHex = colors[pair.foreground];
    const backgroundHex = colors[pair.background];
    if (!foregroundHex || !backgroundHex)
      throw new Error(`Missing token for ${pair.purpose}`);
    return {
      ...pair,
      foregroundHex,
      backgroundHex,
      ratio: contrastRatio(foregroundHex, backgroundHex),
    };
  });
}

export function contrastMarkdown(css: string) {
  const rows = evaluateContrast(css).map(
    (p) =>
      `| ${p.purpose} | ${p.foreground} (${p.foregroundHex}) | ${p.background} (${p.backgroundHex}) | ${p.ratio.toFixed(2)}:1 | ${p.minimum ? `${p.minimum}:1` : 'Informational'} |`,
  );
  return [
    '# Design contrast',
    '',
    'Generated by `pnpm design:contrast` from `apps/web/src/styles/tokens.css` using `apps/web/src/design/contrast.ts`. Do not edit by hand.',
    '',
    'Ratios use WCAG sRGB relative luminance. Normal text requires 4.5:1; meaningful control boundaries and focus indicators require 3:1. Tests compare unrounded ratios. Status tints and dividers are decorative, so their surface contrast has no minimum; status meaning is always present as readable text. Focus rings are offset onto the surrounding white, ice or navy surface. Disabled text also meets 4.5:1 even though disabled controls are exempt.',
    '',
    '| Purpose | Foreground | Background | Ratio | Minimum |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}
